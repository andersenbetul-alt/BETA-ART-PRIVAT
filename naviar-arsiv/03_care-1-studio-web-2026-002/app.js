const supportedLanguages = Object.keys(translations);
let activeLanguage = "nb";

function getInitialLanguage() {
  const params = new URLSearchParams(window.location.search);
  const requested = params.get("lang");
  if (supportedLanguages.includes(requested)) return requested;

  try {
    const saved = window.localStorage.getItem("naviar-care-language");
    if (supportedLanguages.includes(saved)) return saved;
  } catch (error) {
    // Local preference is optional for this static prototype.
  }

  return "nb";
}

function applyLanguage(language, updateUrl = true) {
  if (!supportedLanguages.includes(language)) language = "nb";
  activeLanguage = language;
  const copy = translations[language];

  document.documentElement.lang = language;
  document.title = copy.pageTitle;
  const description = document.querySelector('meta[name="description"]');
  if (description) description.setAttribute("content", copy.pageDescription);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (copy[key] !== undefined) element.textContent = copy[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (copy[key] !== undefined) element.setAttribute("placeholder", copy[key]);
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (copy[key] !== undefined) element.setAttribute("aria-label", copy[key]);
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === language));
  });

  try {
    window.localStorage.setItem("naviar-care-language", language);
  } catch (error) {
    // Local preference is optional for this static prototype.
  }

  if (updateUrl && window.history && window.history.replaceState) {
    const url = new URL(window.location.href);
    url.searchParams.set("lang", language);
    window.history.replaceState({}, "", url);
  }
}

function setupMenu() {
  const toggle = document.querySelector(".menu-toggle");
  const nav = document.querySelector("#primary-nav");
  if (!toggle || !nav) return;

  toggle.addEventListener("click", () => {
    const isOpen = nav.classList.toggle("is-open");
    toggle.setAttribute("aria-expanded", String(isOpen));
    toggle.dataset.i18nAriaLabel = isOpen ? "menuCloseLabel" : "menuLabel";
    toggle.setAttribute("aria-label", translations[activeLanguage][toggle.dataset.i18nAriaLabel] || translations[activeLanguage].menuLabel);
  });

  nav.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", () => {
      nav.classList.remove("is-open");
      toggle.setAttribute("aria-expanded", "false");
      toggle.setAttribute("aria-label", translations[activeLanguage].menuLabel);
    });
  });
}

function setFieldError(field, invalid) {
  if (!field) return;
  field.setAttribute("aria-invalid", String(invalid));
}

function setupForm() {
  const form = document.querySelector("#interest-form");
  const feedback = document.querySelector("#form-feedback");
  if (!form || !feedback) return;

  form.addEventListener("submit", (event) => {
    event.preventDefault();
    const role = form.elements.role;
    const name = form.elements.name;
    const email = form.elements.email;
    const interest = form.elements.interest;
    const consent = form.elements.consent;
    const invalid = [];

    [role, name, email, interest].forEach((field) => setFieldError(field, false));
    consent.removeAttribute("aria-invalid");

    if (!role.value) invalid.push(role);
    if (!name.value.trim()) invalid.push(name);
    if (!email.value.trim() || !email.validity.valid) invalid.push(email);
    if (!interest.value) invalid.push(interest);
    if (!consent.checked) {
      consent.setAttribute("aria-invalid", "true");
      invalid.push(consent);
    }

    if (invalid.length) {
      invalid.forEach((field) => setFieldError(field, true));
      feedback.className = "form-feedback error";
      feedback.textContent = translations[activeLanguage].formError;
      invalid[0].focus();
      return;
    }

    form.reset();
    [role, name, email, interest].forEach((field) => field.removeAttribute("aria-invalid"));
    consent.removeAttribute("aria-invalid");
    feedback.className = "form-feedback";
    feedback.textContent = translations[activeLanguage].formSuccess;
  });
}

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.addEventListener("click", () => applyLanguage(button.dataset.lang));
  });

  setupMenu();
  setupForm();
  applyLanguage(getInitialLanguage(), false);
});
